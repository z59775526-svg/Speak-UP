function t(key, values = {}) {
  const template = translations[state.language]?.[key] ?? translations.uz[key] ?? key;
  return template.replace(/\{(\w+)\}/g, (_, name) => String(values[name] ?? ''));
}

function formatPrice(amount) {
  const number = new Intl.NumberFormat(localeForLanguage[state.language], { maximumFractionDigits: 0 }).format(amount);
  return `${number}\u00a0${t('currency')}`;
}

function applyTranslations() {
  document.documentElement.lang = htmlLanguage[state.language];
  document.title = t('meta.title');
  const description = document.querySelector('meta[name="description"]');
  if (description) description.content = t('meta.description');

  document.querySelectorAll('[data-i18n]').forEach((element) => {
    element.textContent = t(element.dataset.i18n);
  });
  document.querySelectorAll('[data-i18n-placeholder]').forEach((element) => {
    element.setAttribute('placeholder', t(element.dataset.i18nPlaceholder));
  });
  document.querySelectorAll('[data-i18n-aria-label]').forEach((element) => {
    element.setAttribute('aria-label', t(element.dataset.i18nAriaLabel));
  });
  document.querySelectorAll('[data-i18n-alt]').forEach((element) => {
    element.setAttribute('alt', t(element.dataset.i18nAlt));
  });

  document.querySelectorAll('[data-lang]').forEach((button) => {
    const active = button.dataset.lang === state.language;
    button.classList.toggle('is-active', active);
    button.setAttribute('aria-pressed', String(active));
  });

  const themeButton = document.getElementById('themeToggle');
  const themeKey = state.theme === 'dark' ? 'header.themeDark' : 'header.themeLight';
  themeButton.setAttribute('aria-label', t(themeKey));
  themeButton.setAttribute('aria-pressed', String(state.theme === 'dark'));
  themeButton.title = t(themeKey);

  const menuButton = document.getElementById('menuToggle');
  menuButton.setAttribute('aria-label', t(mobileMenuOpen ? 'header.menuClose' : 'header.menuOpen'));
  const mobileNav = document.getElementById('mobileMenu');
  mobileNav.setAttribute('aria-label', t('header.mobileNavigation'));

  renderProducts();
  renderCart();
}

function setLanguage(language) {
  if (!Object.hasOwn(translations, language)) return;
  state.language = language;
  writeStorage(storageKeys.language, language);
  applyTranslations();
}

function setTheme(theme) {
  state.theme = theme;
  document.documentElement.dataset.theme = theme;
  document.querySelector('meta[name="theme-color"]').content = theme === 'dark' ? '#141416' : '#f8f7f5';
  writeStorage(storageKeys.theme, theme);
  applyTranslations();
}

function productById(id) {
  return products.find((product) => product.id === id);
}

function productTitle(product) {
  return product.name;
}

function getFilteredProducts() {
  const query = state.query.trim().toLocaleLowerCase(localeForLanguage[state.language]);
  let filtered = products.filter((product) => {
    const categoryLabel = t(`category.${product.category}`);
    const searchable = [product.name, t(product.description), categoryLabel, ...product.specs]
      .join(' ')
      .toLocaleLowerCase(localeForLanguage[state.language]);
    return (state.filter === 'all' || product.category === state.filter) && (!query || searchable.includes(query));
  });

  if (state.sort === 'price-asc') filtered = [...filtered].sort((a, b) => a.price - b.price);
  if (state.sort === 'price-desc') filtered = [...filtered].sort((a, b) => b.price - a.price);
  return filtered;
}

