function persistCart() {
  writeStorage(storageKeys.cart, [...state.cart.entries()]);
}

function addToCart(id) {
  const product = productById(id);
  if (!product) return;
  state.cart.set(id, (state.cart.get(id) || 0) + 1);
  persistCart();
  renderCart();
  showToast(t('shop.added', { name: productTitle(product) }));
}

function renderCart() {
  if (!cartItems) return;
  const lines = [...state.cart.entries()].filter(([id, quantity]) => productById(id) && quantity > 0);
  const itemCount = lines.reduce((total, [, quantity]) => total + quantity, 0);
  const total = lines.reduce((sum, [id, quantity]) => sum + productById(id).price * quantity, 0);
  const cartCount = document.getElementById('cartCount');
  cartCount.textContent = String(itemCount);
  document.getElementById('drawerCount').textContent = `(${itemCount})`;
  document.getElementById('cartTotal').textContent = formatPrice(total);
  document.getElementById('cartTrigger').setAttribute('aria-label', `${t('header.cart')} (${itemCount})`);
  cartEmpty.hidden = lines.length !== 0;
  drawerFooter.hidden = lines.length === 0;
  cartItems.hidden = lines.length === 0;

  cartItems.innerHTML = lines.map(([id, quantity]) => {
    const product = productById(id);
    return `
      <article class="cart-line" data-id="${product.id}">
        <img src="${product.image}" alt="${t(product.alt)}" />
        <div>
          <h3 class="cart-line-title">${productTitle(product)}</h3>
          <span class="cart-line-price">${formatPrice(product.price * quantity)}</span>
          <div class="cart-line-controls">
            <button class="qty-button" type="button" data-cart-action="decrease" data-id="${product.id}" aria-label="${t('cart.decrease')}"><svg class="icon"><use href="#i-minus" /></svg></button>
            <span class="qty-value">${quantity}</span>
            <button class="qty-button" type="button" data-cart-action="increase" data-id="${product.id}" aria-label="${t('cart.increase')}"><svg class="icon"><use href="#i-plus" /></svg></button>
          </div>
        </div>
        <button class="remove-line" type="button" data-cart-action="remove" data-id="${product.id}" aria-label="${t('cart.remove')}"><svg class="icon"><use href="#i-close" /></svg></button>
      </article>`;
  }).join('');
}

