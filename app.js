document.addEventListener('keydown', (event) => {
  if (event.key === 'Escape') {
    if (!quickOverlay.hidden) closeQuickView();
    else if (!cartOverlay.hidden) closeCart();
    else if (mobileMenuOpen) updateMobileMenu(false);
  }

  const activeOverlay = !quickOverlay.hidden ? quickOverlay : (!cartOverlay.hidden ? cartOverlay : null);
  if (event.key === 'Tab' && activeOverlay) {
    const focusable = [...activeOverlay.querySelectorAll('button:not([disabled]), a[href], input:not([disabled]), select:not([disabled])')]
      .filter((element) => element.offsetParent !== null);
    if (!focusable.length) return;
    const first = focusable[0];
    const last = focusable[focusable.length - 1];
    if (event.shiftKey && document.activeElement === first) {
      event.preventDefault();
      last.focus();
    } else if (!event.shiftKey && document.activeElement === last) {
      event.preventDefault();
      first.focus();
    }
  }
});

